"""Builds assets/fonts/Coolicons.ttf + lib/core/theme/cool_icons.dart from the
Coolicons SVG pack (MIT) for exactly the glyphs in icon_map.py.

Usage (from the project root, with picosvg + fonttools installed):
  python tool/coolicons/build_font.py assets/icons/coolicons-5.2.0

Line icons are strokes; picosvg turns them into filled outlines so they can
live in a font. Re-run whenever icon_map.py changes.
"""
import os
import re
import sys

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path
from picosvg.svg import SVG

sys.path.insert(0, os.path.dirname(__file__))
from icon_map import MAP  # noqa: E402

PACK = sys.argv[1]
UPM = 1024
SCALE = UPM / 24.0
FIRST_CP = 0xE000


def camel(style, name):
    parts = re.split(r"[-_]", name)
    base = parts[0] + "".join(p.capitalize() for p in parts[1:])
    if base[0].isdigit():
        base = "i" + base
    return base + ("Fill" if style == "fill" else "")


glyphs = sorted(set(MAP.values()))
order = [".notdef"]
cmap = {}
outlines = {}
fields = {}

for i, (style, name) in enumerate(glyphs):
    path = os.path.join(PACK, "svg", style, "round", f"{name}.svg")
    pico = SVG.parse(path).topicosvg()
    tt = TTGlyphPen(None)
    pen = Cu2QuPen(TransformPen(tt, (SCALE, 0, 0, -SCALE, 0, 24 * SCALE)), max_err=1.0, reverse_direction=True)
    for shape in pico.shapes():
        parse_path(shape.as_path().d, pen)
    gname = f"{style}_{name}".replace("-", "_")
    order.append(gname)
    cp = FIRST_CP + i
    cmap[cp] = gname
    outlines[gname] = tt.glyph()
    fields[(style, name)] = (camel(style, name), cp)

outlines[".notdef"] = TTGlyphPen(None).glyph()

fb = FontBuilder(UPM, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(outlines)
fb.setupHorizontalMetrics({g: (UPM, 0) for g in order})
fb.setupHorizontalHeader(ascent=UPM, descent=0)
# A complete name table: App Store Connect rejects a font missing the full,
# PostScript, version or unique-ID names (ITMS-90853 "'name' table usability").
fb.setupNameTable({
    "copyright": "Icons: Coolicons by Kryston Schwarze (MIT License)",
    "familyName": "Coolicons",
    "styleName": "Regular",
    "uniqueFontIdentifier": "Coolicons-Regular;1.000;1-2-1 Connect",
    "fullName": "Coolicons Regular",
    "version": "Version 1.000",
    "psName": "Coolicons-Regular",
})
fb.setupOS2(sTypoAscender=UPM, sTypoDescender=0, sTypoLineGap=0, usWinAscent=UPM, usWinDescent=0)
fb.setupPost()
os.makedirs("assets/fonts", exist_ok=True)
fb.save("assets/fonts/Coolicons.ttf")

lines = [
    "// GENERATED by tool/coolicons/build_font.py — do not edit by hand.",
    "// Coolicons (MIT, Kryston Schwarze), the subset this app uses.",
    "import 'package:flutter/widgets.dart';",
    "",
    "/// The app's icon set. Drop-in for Material `Icons.*` (same IconData type).",
    "abstract final class CoolIcons {",
]
for (style, name), (field, cp) in sorted(fields.items(), key=lambda kv: kv[1][0]):
    lines.append(f"  static const IconData {field} = IconData(0x{cp:X}, fontFamily: 'Coolicons');")
lines.append("}")
open("lib/core/theme/cool_icons.dart", "w").write("\n".join(lines) + "\n")

# Material name -> CoolIcons field, for the code rewrite.
with open("tool/coolicons/replacements.tsv", "w") as f:
    for mat, key in sorted(MAP.items()):
        f.write(f"{mat}\t{fields[key][0]}\n")
print(f"{len(glyphs)} glyphs -> assets/fonts/Coolicons.ttf, lib/core/theme/cool_icons.dart")
